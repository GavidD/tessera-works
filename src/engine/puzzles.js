function parse([id, points, reward, rows], tier) {
  const cells = [];
  rows.forEach((row, y) => [...row].forEach((ch, x) => { if (ch === '#') cells.push([x, y]); }));
  return {
    id, tier, points, reward, cells,
    width: Math.max(...rows.map(r => r.length)),
    height: rows.length,
  };
}

const PUZZLES = {};
for (const tier of ['bronze', 'gold']) {
  for (const raw of RAW[tier]) PUZZLES[raw[0]] = parse(raw, tier);
}

const deckIds = tier => RAW[tier].map(r => r[0]);

module.exports = { PUZZLES, deckIds };
